/** 命中条目渲染：`- id (score N, scope)` + 前 8 行预览。 */
export function formatMemorySearchHit(file: MemoryFile & { score: number }): string {
  const preview = file.content.split('\n').slice(0, 8).join('\n')
  return `- ${file.id} (score ${String(file.score)}, ${file.scope})\n${preview}`
}

/** 行号前缀渲染（`N→content`，与 hashline 的 LINE_NUMBER→ 约定一致）。 */
export function formatMemoryNumbered(content: string, from = 1, lines?: number): string {
  const all = content.split('\n')
  const start = Math.max(1, from) - 1
  const slice = lines === undefined ? all.slice(start) : all.slice(start, start + lines)
  return slice.map((line, index) => `${String(start + index + 1)}→${line}`).join('\n')
}
